"""Pydantic schemas for feature engineering sets."""

import uuid
from datetime import datetime
from pydantic import BaseModel, Field


class FeatureGenerateRequest(BaseModel):
    """Request payload to engineer a new feature set."""

    name: str = Field(..., max_length=255, description="Unique name for this feature set")
    method: str = Field(..., description="date, interaction, polynomial, text, pca, selection")
    config: dict = Field(..., description="Parameters required for the selected method")


class FeatureSetRead(BaseModel):
    """Full detail of a registered FeatureSet."""

    id: uuid.UUID
    dataset_id: uuid.UUID
    name: str
    features: list[dict]
    output_file_path: str | None = None
    feature_count: int
    method: str
    created_at: datetime

    model_config = {"from_attributes": True}


class FeaturePreviewResponse(BaseModel):
    """Previews the new columns and sample rows generated by feature engineering."""

    columns: list[str]
    rows: list[dict]
